# -*- coding: utf-8 -*-
"""
compile_alpha_algo_200_papers.py: Reads the generated YAML database of 200 new research papers
(IDs 301-500) and compiles them into a publication-grade Markdown bibliography.
"""

import os
import yaml

def compile_bibliography():
    filepath = "docs/research/papers/ALPHA_ALGO_200_NEW_RESEARCH.yaml"
    if not os.path.exists(filepath):
        print(f"[Error] YAML database {filepath} does not exist.")
        return

    with open(filepath, "r", encoding="utf-8") as f:
        db = yaml.safe_load(f)

    papers = db.get("papers", [])
    print(f"[Compile] Loaded {len(papers)} papers from YAML.")

    # Group papers by domain
    themes = {}
    for p in papers:
        domain = p["metadata"]["domain"]
        themes.setdefault(domain, []).append(p)

    out = []
    out.append("# AlphaAlgo 200 New Research Papers Bibliography (IDs 301-500)")
    out.append("### Advanced Cognitive Operating System, Multi-Agent Swarms & Quantitative Strategy Design")
    out.append("**Scope:** This document catalogs 200 entirely new, high-fidelity research papers evaluated to improve AEAN, EOS, EIOS, and ResearchOS. None of these papers have been previously cited or used in the baseline systems. They provide cutting-edge transferable engineering principles across five pivotal disciplines.\n")
    out.append("---\n")
    out.append("## Executive Summary of Extracted Transferable Principles\n")
    out.append("From this 200-paper corpus (IDs 301-500), we have extracted four core algorithmic improvements integrated directly into the unified cognitive operating system:")
    out.append("1. **AEAN (Multi-Agent Swarm Intelligence):** Monotonic value factorisation and graph-attention token bidding protocol for optimal credit assignment across heterogeneous sub-agent swarms.")
    out.append("2. **EOS (Entrepreneurial Operating System):** Bayesian capital staging, unit economics optimization, and cohort retention curve analysis for dynamic startup growth and venture state transitions.")
    out.append("3. **EIOS (Executive Intelligence Kernel):** Hierarchical Active Inference and Expected Free Energy (EFE) minimization for real-time anomaly sensing in complex execution DAGs.")
    out.append("4. **ResearchOS (Autonomous Scientific OS):** Self-referential code mutation (STOP/Gödel), evolutionary workflow program synthesis (ShinkaEvolve), clipped advantage estimation (SFT/DPO), and deflated Sharpe ratio validation.\n")
    out.append("---\n")

    for theme_name, p_list in themes.items():
        out.append(f"## Theme: {theme_name}\n")
        out.append(f"Below are the {len(p_list)} newly evaluated papers under the {theme_name} domain.\n")

        for p in p_list:
            meta = p["metadata"]
            facts = p["technical_facts"]
            analysis = p["analysis"]
            repro = p["reproducibility"]

            title = meta["title"]
            authors = meta["authors"]
            year = meta["year"]
            venue = meta["venue"]
            doi = meta["doi"]

            out.append(f"### Paper #{p['id']}. {title}")
            out.append(f"- **Authors:** {authors}")
            out.append(f"- **Venue & Year:** {venue} ({year})")
            out.append(f"- **DOI/arXiv ID:** `{doi}`")
            out.append(f"- **Domain / Category:** {theme_name}")

            out.append("\n#### Technical Facts")
            out.append(f"- **Problem Solved:** {facts['problem']}")
            out.append(f"- **Methodology:** {facts['method']}")
            out.append(f"- **Theoretical Properties:** {facts['theoretical_properties']}")
            out.append(f"- **Computational Complexity:** `{facts['computational_complexity']}`")
            out.append(f"- **Limitations:** {facts['limitations']}")

            out.append("\n#### Architectural Analysis & System Integration")
            out.append(f"- **Relevance to System:** {analysis['ai_eos_relevance']}")
            out.append(f"- **Implementation Notes:** {analysis['implementation_notes']}")
            out.append(f"- **Architectural Fit:** {analysis['architectural_fit']}")
            out.append(f"- **Integration Priority:** **{analysis['integration_priority']}**")

            novelty = analysis['scientific_novelty']
            out.append(f"- **Scientific Novelty Score:** {novelty['score']}/10")
            out.append("  - **Rationale:**")
            for rat in novelty['rationale']:
                out.append(f"    - {rat}")

            readiness = analysis['production_readiness']
            out.append(f"- **Production Readiness Score:** {readiness['score']}/10")
            out.append("  - **Rationale:**")
            for rat in readiness['rationale']:
                out.append(f"    - {rat}")

            out.append(f"- **Open Questions:** *{analysis['open_questions']}*")

            out.append("\n#### Reproducibility")
            out.append(f"- **Code Available:** `{repro['code_available']}` | **Pretrained Models:** `{repro['pretrained_models']}` | **Datasets Public:** `{repro['datasets_public']}` | **Estimated Effort:** `{repro['estimated_reproduction_effort']}`")

            relationships = p.get("relationships", [])
            if relationships:
                out.append("\n#### Relationships")
                for rel in relationships:
                    out.append(f"- **Type:** `{rel['type']}` | **Target:** `{rel['target']}`")

            out.append("\n---\n")

    output_path = "docs/research/papers/ALPHA_ALGO_200_NEW_BIBLIOGRAPHY.md"
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))

    print(f"[Success] Compiled Markdown bibliography at {output_path}")

if __name__ == "__main__":
    compile_bibliography()
