# -*- coding: utf-8 -*-
"""
test_unified_5layer_integration.py: Complete end-to-end multi-layer integration test suite
validating joint operations across:
- Layer 1: Research OS
- Layer 2: EIOS Kernel & EOS Engine
- Layer 3: AEAN HiveMind
- Layer 4: APODEX WorldModel
"""

from __future__ import annotations
import pytest
from uuid import UUID

from apodex.ai_eos.research.research_os import ResearchOS
from apodex.arcs.kernel.kernel import EIOSKernel, EntrepreneurialCompiler
from apodex.ai_eos.intelligence.eos_engine import EOSEngine
from apodex.aean.coordination.hive_mind import HiveMind, TaskBid
from apodex.world_model.world_model import WorldModel
from apodex.ai_eos.research.integration import ResearchToSystemBridge


def test_unified_5layer_pipeline_execution():
    """Verify end-to-end active inference state handoffs across all 5 cognitive subsystems."""
    # Initialize all 5 subsystems
    ros = ResearchOS()
    kernel = EIOSKernel()
    eos = EOSEngine()
    hive = HiveMind(token_budget=100)
    world = WorldModel()

    # Construct the unified ResearchToSystemBridge
    bridge = ResearchToSystemBridge(
        research_os=ros,
        kernel=kernel,
        eos_engine=eos,
        hive_mind=hive,
        world_model=world
    )

    # Execute complete research-to-system pipeline
    res = bridge.execute_full_research_pipeline(
        title="GRPO Active Inference Acceleration",
        description="Verify Expected Free Energy optimization reduces active inference latency",
        target_metric="latency_reduction_ms",
        ground_truth_yield=2.5
    )

    # 1. Assert Layer 1 Research OS outcomes
    assert res["is_validated"] is True
    assert res["status"] == "validated"
    assert res["p_value"] < 0.05

    # 2. Assert Layer 2 EIOS Kernel ingestion & Active Inference anomaly sensing
    assert len(kernel.registered_hypotheses) == 1
    assert kernel.registered_hypotheses[0]["title"] == "GRPO Active Inference Acceleration"

    anomalies = kernel.sense_opportunity_anomalies()
    assert len(anomalies) == 1
    assert anomalies[0]["expected_free_energy"] == 0.35

    # 3. Assert Layer 2 EOS Engine active hypothesis ingestion
    active_hyps = eos.active_hypotheses
    assert len(active_hyps) == 1
    assert active_hyps[0]["title"] == "GRPO Active Inference Acceleration"

    # 4. Assert Layer 3 AEAN HiveMind insight registration & token bidding arbitration
    assert len(hive.registered_insights) == 1
    assert hive.registered_insights[0]["priority"] == 0.9

    bid = hive.submit_research_bid(
        task_name="Deploy GRPO Agent",
        priority=0.9,
        expected_value=1.5,
        token_cost=20
    )
    grants = hive.arbitrate([bid])
    assert len(grants) == 1
    assert grants[0].granted is True
    assert grants[0].tokens == 20

    # 5. Assert Layer 4 APODEX WorldModel causal node and Bayesian belief updates
    hyp_id = res["hypothesis_id"]
    node_id = f"research_hyp_{hyp_id}"
    assert node_id in world.nodes
    assert hyp_id in world.beliefs
    assert world.beliefs[hyp_id]["validated"] is True
    assert world.beliefs[hyp_id]["posterior_probability"] == 0.95


@pytest.mark.asyncio
async def test_eios_dag_execution_with_eos_compiler():
    """Verify EIOS Kernel DAG execution generated by EntrepreneurialCompiler."""
    compiler = EntrepreneurialCompiler()
    kernel = EIOSKernel()

    dag = compiler.compile_goal_to_dag(goal="Launch AI SaaS Venture", target_budget_usd=10000)
    assert len(dag.nodes) == 4

    success = await kernel.execute_dag(dag)
    assert success is True
    assert all(node.status == "COMPLETED" for node in dag.nodes.values())
